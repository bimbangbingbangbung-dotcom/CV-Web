/**
 * Generates src/utils/content-validator.generated.ts — a dependency-free,
 * browser-side validator compiled from content.schema.json via Ajv's
 * standalone codegen.
 *
 * Why generate at build time? The full Ajv runtime (~35 KB gzipped) would
 * blow the < 50 KB public JS budget on its own. Compiling the schema to
 * plain functions keeps runtime validation exact AND tiny, while the schema
 * file stays the single source of truth (Ajv is a dev-only dependency).
 *
 * Run: npm run gen:validator (also runs before dev/build automatically)
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = path.join(root, 'content.schema.json');
const outPath = path.join(root, 'src', 'utils', 'content-validator.generated.ts');

const { default: Ajv2020 } = await import('ajv/dist/2020.js');
const { default: addFormats } = await import('ajv-formats');
const { default: standaloneCode } = await import('ajv/dist/standalone/index.js');

const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
const ajv = new Ajv2020({ strict: true, allErrors: true, allowUnionTypes: true });
addFormats(ajv);

const validate = ajv.compile(schema);
let code = standaloneCode(ajv, validate);

// Ajv standalone emits CommonJS; the browser bundle needs ESM. Transform the
// export lines rather than bundling a CJS shim. Fail loudly if Ajv's output
// shape ever changes instead of shipping a broken validator.
const rootExport = 'module.exports = validate;';
if (!code.includes(rootExport)) {
  console.error('generate-validator: unexpected Ajv standalone output. Head of file:');
  console.error(code.slice(0, 500));
  process.exit(1);
}
code = code
  .replace('"use strict";', '')
  .replace(rootExport, '')
  .replace(/module\.exports\.default\s*=\s*validate;/, '')
  .trim();

const header = [
  '/* eslint-disable */',
  '// @ts-nocheck',
  '// ---------------------------------------------------------------',
  '// AUTO-GENERATED by scripts/generate-validator.mjs — do not edit.',
  '// Source of truth: content.schema.json. Regenerate with:',
  '//   npm run gen:validator',
  '// ---------------------------------------------------------------',
  '',
].join('\n');

await writeFile(outPath, `${header}${code}\n\nexport default validate;\n`, 'utf8');
console.log(
  `generate-validator: wrote ${path.relative(root, outPath)} (${(code.length / 1024).toFixed(1)} KB)`,
);
